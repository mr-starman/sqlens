// Regenerates the vendored frontend assets in src/main/webapp/vendor.
// Run with `npm install && npm run build` after changing versions in package.json,
// then commit the output. The Maven build only uses the committed files.
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const out = new URL('../src/main/webapp/vendor/', import.meta.url);
mkdirSync(out, { recursive: true });

await build({
  entryPoints: ['codemirror-entry.js'],
  bundle: true,
  format: 'esm',
  minify: true,
  target: 'es2020',
  legalComments: 'eof',
  outfile: new URL('codemirror.js', out).pathname,
});

const font = 'node_modules/@fontsource-variable/jetbrains-mono/';
copyFileSync(font + 'files/jetbrains-mono-latin-wght-normal.woff2', new URL('jetbrains-mono-latin.woff2', out));
copyFileSync(font + 'files/jetbrains-mono-latin-ext-wght-normal.woff2', new URL('jetbrains-mono-latin-ext.woff2', out));
copyFileSync(font + 'LICENSE', new URL('jetbrains-mono-OFL.txt', out));

const versions = ['@codemirror/state', '@codemirror/view', '@codemirror/commands', '@codemirror/language',
  '@codemirror/search', '@codemirror/autocomplete', '@codemirror/lang-sql', '@lezer/highlight',
  '@fontsource-variable/jetbrains-mono']
  .map(name => `${name} ${JSON.parse(readFileSync(`node_modules/${name}/package.json`)).version}`);
writeFileSync(new URL('VERSIONS.txt', out),
  'Generated by frontend/build.mjs. CodeMirror is MIT licensed; JetBrains Mono is under the SIL Open Font License.\n\n'
  + versions.join('\n') + '\n');
console.log('Wrote', out.pathname);
